"""Render the dictionary as one markdown page (docs/wiki/Econ-Dictionary.md). Generated: edit the YAML."""
from __future__ import annotations

from collections import defaultdict

from .graph import EconGraph


def _cell(v) -> str:
    if v is None:
        return ""
    if isinstance(v, (list, tuple)):
        v = ", ".join(map(str, v))
    return str(v).replace("|", "/").replace("\n", " ")


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return out + [""]


def render(g: EconGraph) -> str:
    s = g.summary()
    L = ["# Economic dictionary", "",
         "_Generated by `mlab econ docs` from `src/mlab/econ/data/*.yaml`; edit the YAML, then regenerate._", "",
         "Nodes: " + ", ".join(f"{k} {v}" for k, v in s["nodes"].items()) + ". Edges: "
         + ", ".join(f"{k} {v}" for k, v in s["edges"].items()) + ".", "",
         "Kinds: `ind` industry, `sig` indicator, `kpi` unit-economics KPI, `src` source, `mkt` tradable proxy, "
         + "`cls` classification code. See [[Econ Graph]] for how to traverse it.", ""]

    L += ["## Industry tree", ""]
    kids = defaultdict(list)
    for n in g.of_kind("ind"):
        kids[n.data.get("parent")].append(n)

    def tree(parent, depth):
        for n in sorted(kids[parent], key=lambda x: x.key):
            codes = "; ".join(f"{k.upper()} {_cell(n.data[k])}" for k in ("naics", "uksic", "hs") if n.data.get(k))
            L.append(f"{'  ' * depth}- **{n.key}**: {n.name}" + (f" ({codes})" if codes else ""))
            tree(n.key, depth + 1)
    tree(None, 0)
    L.append("")

    L += ["## Indicators", ""]
    by_layer = defaultdict(list)
    for n in g.of_kind("sig"):
        by_layer[n.data.get("layer")].append(n)
    for layer in ("macro", "meso", "micro"):
        rows = [[f"`{n.key}`", n.name, n.data.get("geo"), n.data.get("freq"), n.data.get("cycle"),
                 "; ".join(f"{x['source']}:{x['id']}" for x in n.data.get("series", [])), n.data.get("industries")]
                for n in sorted(by_layer[layer], key=lambda x: (x.data.get("geo", ""), x.key))]
        L += [f"### {layer.capitalize()} ({len(rows)})", ""]
        L += _table(["id", "name", "geo", "freq", "cycle", "series", "measures"], rows)

    L += ["## Unit-economics KPIs", ""]
    L += _table(["id", "name", "formula", "unit", "better", "applies to"],
                [[f"`{n.key}`", n.name, n.data.get("formula"), n.data.get("unit"), n.data.get("better"),
                  n.data.get("applies_to")] for n in sorted(g.of_kind("kpi"), key=lambda x: x.key)])

    L += ["## Sources", "", "`storage`: may the data be frozen into our offline store. `no`, `conditional` and "
          + "`unverified` mean fetch live and keep in memory until the terms are cleared.", ""]
    L += _table(["id", "name", "region", "access", "cost", "commercial", "storage", "verified", "licence"],
                [[f"`{n.key}`", n.name, n.data.get("region"), n.data.get("access"), n.data.get("cost"),
                  n.data.get("commercial_use"), n.data.get("storage_allowed"), n.data.get("verified"),
                  f"[{_cell(n.data.get('licence'))[:80]}]({n.data['licence_url']})" if n.data.get("licence_url")
                  else n.data.get("licence")]
                 for n in sorted(g.of_kind("src"), key=lambda x: (x.data.get("region", ""), x.key))])

    L += ["## Tradable proxies", ""]
    L += _table(["id", "name", "ticker", "kind", "industries", "discloses"],
                [[f"`{n.key}`", n.name, n.data.get("ticker"), n.data.get("kind"), n.data.get("industries"),
                  n.data.get("discloses")] for n in sorted(g.of_kind("mkt"), key=lambda x: x.key)])

    L += ["## Economic links (explicit edges)", "", "`prior` = desk prior, untested; a candidate for the lead-lag "
          + "discovery, not a fact.", ""]
    L += _table(["from", "type", "to", "sign", "lag (months)", "evidence", "cite / note"],
                [[e.src, e.type, e.dst, e.attrs.get("sign"), e.attrs.get("lag"), e.attrs.get("evidence"),
                  e.attrs.get("cite") or e.attrs.get("note")]
                 for e in g.edges if e.type in ("drives", "leads", "input_to")])
    return "\n".join(L)
